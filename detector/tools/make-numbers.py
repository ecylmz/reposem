#!/usr/bin/env python3
"""Write one LaTeX macro for each value in a numbers JSON file.

Usage: make-numbers.py results/numbers.json paper/numbers.tex

The JSON file is a flat object. A value is one of these:
  an integer                         18
  a string, written as plain text    "RA-SZZ"  (LaTeX special characters are escaped)
  a rounded number                   {"value": 0.78123, "digits": 3}
  a LaTeX fragment, written as is    {"latex": "$p < 0.001$"}
A real number without "digits" is an error, so that every rounding is a decision in the analysis script. NaN,
Infinity, and repeated keys are errors. Rounding is half up on the exact decimal in the file.
"""
import decimal
import hashlib
import json
import re
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ESCAPES = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&", "#": r"\#", "%": r"\%",
           "_": r"\_", "^": r"\textasciicircum{}", "~": r"\textasciitilde{}", "<": r"\textless{}",
           ">": r"\textgreater{}"}


def no_duplicates(pairs):
    keys = [k for k, _ in pairs]
    dup = sorted({k for k in keys if keys.count(k) > 1})
    if dup:
        raise ValueError("repeated keys: " + ", ".join(dup))
    return dict(pairs)


def no_constant(name):
    raise ValueError(f"{name} is not a number")


def fmt(name, v):
    if isinstance(v, dict) and set(v) == {"latex"} and isinstance(v["latex"], str):
        return v["latex"]
    if isinstance(v, dict) and set(v) == {"value", "digits"}:
        num, digits = v["value"], v["digits"]
        if type(num) not in (int, Decimal) or type(digits) is not int or digits < 0:
            raise ValueError(f"{name}: value must be a number and digits a non-negative integer")
        num = Decimal(num)
        with decimal.localcontext() as ctx:
            ctx.prec = max(28, num.adjusted() + digits + 2)
            d = num.quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)
        return format(abs(d) if d == 0 else d, "f")
    if isinstance(v, dict):
        raise ValueError(f"{name}: expected {{value, digits}} or {{latex}}, got keys {sorted(v)}")
    if type(v) is int:
        return str(v)
    if isinstance(v, Decimal):
        raise ValueError(f"{name}: a real number needs {{\"value\": ..., \"digits\": ...}}")
    if isinstance(v, str):
        return "".join(ESCAPES.get(c, c) for c in v)
    raise ValueError(f"{name}: unsupported value {v!r}")


def main(src, dst):
    raw = Path(src).read_bytes()
    try:
        data = json.loads(raw, parse_float=Decimal, parse_constant=no_constant, object_pairs_hook=no_duplicates)
    except ValueError as e:
        sys.exit(f"make-numbers: {src}: {e}")
    if not isinstance(data, dict):
        sys.exit("make-numbers: the JSON file must hold one object")
    lines = [f"% Generated by make-numbers.py from {src} (sha256 {hashlib.sha256(raw).hexdigest()[:12]}). Do not edit."]
    errors = []
    for name, v in data.items():
        if not re.fullmatch(r"[A-Za-z]+", name) or name.startswith("end"):
            errors.append(f"{name}: a macro name has letters only and does not start with 'end'")
            continue
        try:
            lines.append(f"\\newcommand{{\\{name}}}{{{fmt(name, v)}}}")
        except (ValueError, decimal.DecimalException) as e:
            errors.append(str(e))
    if errors:
        sys.exit("make-numbers:\n  " + "\n  ".join(errors))
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    Path(dst).write_text("\n".join(lines) + "\n")
    print(f"make-numbers: {len(data)} macros written to {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().splitlines()[2])
    main(sys.argv[1], sys.argv[2])
